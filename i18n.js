export function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    return saved === 'en' ? 'en' : 'vi';
  } catch {
    return 'vi';
  }
}

export function tr(vi, en) {
  return getLang() === 'en' ? en : vi;
}

export function t(key) {
  const lang = getLang();
  return DICT[lang]?.[key] ?? DICT.vi[key] ?? key;
}

export function syncLangButtons() {
  const lang = getLang();
  document.querySelectorAll('[data-set-lang]').forEach(btn => {
    const active = btn.dataset.setLang === lang;
    btn.classList.toggle('is-active', active);
    btn.setAttribute('aria-pressed', String(active));
  });
  window.__syncSettingsUI?.();
}

export function applyTranslations() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.title = t('app.title');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const val = DICT[lang]?.[el.dataset.i18n];
    if (val !== undefined) el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const val = DICT[lang]?.[el.dataset.i18nPlaceholder];
    if (val !== undefined) el.setAttribute('placeholder', val);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const val = DICT[lang]?.[el.dataset.i18nTitle];
    if (val !== undefined) el.setAttribute('title', val);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const val = DICT[lang]?.[el.dataset.i18nAria];
    if (val !== undefined) el.setAttribute('aria-label', val);
  });
  syncLangButtons();
}

export function setLang(lang) {
  const next = lang === 'en' ? 'en' : 'vi';
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {}
  applyTranslations();
  window.dispatchEvent(new CustomEvent('app:lang-change', { detail: { lang: next } }));
}

export function toggleLang() {
  setLang(getLang() === 'en' ? 'vi' : 'en');
}

export function initI18n() {
  applyTranslations();
  document.querySelectorAll('[data-set-lang]').forEach(btn => {
    if (btn.dataset.i18nBound) return;
    btn.dataset.i18nBound = '1';
    btn.addEventListener('click', () => {
      if (btn.dataset.setLang !== getLang()) setLang(btn.dataset.setLang);
    });
  });
}
